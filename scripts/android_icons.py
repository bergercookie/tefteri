"""Draws the Tefteri notebook mark into the Android launcher icons.

Mirrors `TefteriMark` in frontend/lib/theme/logo.dart. Run from the repository
root: `python3 scripts/android_icons.py` (needs Pillow).
"""

from pathlib import Path

from PIL import Image, ImageDraw

RES = Path("frontend/android/app/src/main/res")
PAPER = (0xFB, 0xF8, 0xF1)
COVER = (0x2F, 0x4B, 0x7C)
RIBBON = (0xD6, 0x49, 0x33)
LINES = tuple(round(c * 0.7 + p * 0.3) for c, p in zip(PAPER, COVER))
SPINE = tuple(round(c * 0.82) for c in COVER)
SS = 8  # supersampling factor


def mark(img: Image.Image, cx: float, cy: float, scale: float) -> None:
    """Draws the 28-unit mark with its centre at (cx, cy)."""
    d = ImageDraw.Draw(img)

    def p(x: float, y: float) -> tuple[float, float]:
        return (cx + (x - 14) * scale, cy + (y - 14) * scale)

    d.rounded_rectangle([p(4, 1), p(24, 27)], radius=3 * scale, fill=COVER)
    for y in (9, 14, 19):
        d.line([p(9, y), p(19, y)], fill=LINES, width=round(1.5 * scale))
        for x in (9, 19):
            r = 0.75 * scale
            a, b = p(x, y)
            d.ellipse([a - r, b - r, a + r, b + r], fill=LINES)
    d.rounded_rectangle([p(4, 1), p(7, 27)], radius=1.5 * scale, fill=SPINE)
    d.polygon([p(17, 1), p(21, 1), p(21, 9), p(19, 7.2), p(17, 9)], fill=RIBBON)


def legacy(size: int) -> Image.Image:
    big = size * SS
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    ImageDraw.Draw(img).rounded_rectangle(
        [0, 0, big - 1, big - 1], radius=big * 0.22, fill=PAPER
    )
    mark(img, big / 2, big / 2, big * 0.66 / 26)
    return img.resize((size, size), Image.LANCZOS)


def vector() -> str:
    """The adaptive-icon foreground: the mark in a 108dp canvas, inside the safe zone."""
    s = 56 / 26

    def p(x: float, y: float) -> str:
        return f"{54 + (x - 14) * s:.2f},{54 + (y - 14) * s:.2f}"

    def rrect(x0, y0, x1, y1, r):
        r *= s
        a, b = 54 + (x0 - 14) * s, 54 + (y0 - 14) * s
        c, e = 54 + (x1 - 14) * s, 54 + (y1 - 14) * s
        return (
            f"M{a + r:.2f},{b:.2f}H{c - r:.2f}A{r:.2f},{r:.2f} 0 0 1 {c:.2f},{b + r:.2f}"
            f"V{e - r:.2f}A{r:.2f},{r:.2f} 0 0 1 {c - r:.2f},{e:.2f}H{a + r:.2f}"
            f"A{r:.2f},{r:.2f} 0 0 1 {a:.2f},{e - r:.2f}V{b + r:.2f}"
            f"A{r:.2f},{r:.2f} 0 0 1 {a + r:.2f},{b:.2f}Z"
        )

    def hexc(c):
        return "#%02X%02X%02X" % c

    lines = "".join(f"M{p(9, y)}L{p(19, y)}" for y in (9, 14, 19))
    ribbon = f"M{p(17, 1)}L{p(21, 1)}L{p(21, 9)}L{p(19, 7.2)}L{p(17, 9)}Z"
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{hexc(COVER)}" android:pathData="{rrect(4, 1, 24, 27, 3)}" />
    <path android:strokeColor="{hexc(LINES)}" android:strokeWidth="{1.5 * s:.2f}"
        android:strokeLineCap="round" android:pathData="{lines}" />
    <path android:fillColor="{hexc(SPINE)}" android:pathData="{rrect(4, 1, 7, 27, 1.5)}" />
    <path android:fillColor="{hexc(RIBBON)}" android:pathData="{ribbon}" />
</vector>
"""


def main() -> None:
    for density, size in {
        "mdpi": 48,
        "hdpi": 72,
        "xhdpi": 96,
        "xxhdpi": 144,
        "xxxhdpi": 192,
    }.items():
        legacy(size).save(RES / f"mipmap-{density}" / "ic_launcher.png")
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(
        """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""
    )
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(vector())
    (RES / "values" / "ic_launcher_background.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#{PAPER[0]:02X}{PAPER[1]:02X}{PAPER[2]:02X}</color>
</resources>
"""
    )


if __name__ == "__main__":
    main()
